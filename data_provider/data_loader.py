class Dataset_Custom(Dataset):
    def __init__(self, root_path, flag='train', size=None,
                 features='S', data_path='ETTh1.csv',
                 target='OT', scale=True, timeenc=0, freq='h',
                 cloud_dir=None, img_size=64, img_channel=1,
                 scaler_path=None, freeze_scaler=False):
        # size [seq_len, label_len, pred_len]
        # info
        if size == None:
            self.seq_len = 24 * 4 * 4
            self.label_len = 24 * 4
            self.pred_len = 24 * 4
        else:
            self.seq_len = size[0]
            self.label_len = size[1]
            self.pred_len = size[2]
        # init
        assert flag in ['train', 'test', 'val']
        type_map = {'train': 0, 'val': 1, 'test': 2}
        self.set_type = type_map[flag]

        self.features = features
        self.target = target
        self.scale = scale
        self.timeenc = timeenc
        self.freq = freq
        self.cloud_dir = cloud_dir
        self.img_size = img_size
        self.img_channel = img_channel
        self.scaler_path = scaler_path
        self.freeze_scaler = freeze_scaler

        self.root_path = root_path
        self.data_path = data_path
        self.__read_data__()

    def __read_data__(self):
        self.scaler = MinMaxScaler(feature_range=(0, 1))
        df_raw = pd.read_csv(os.path.join(self.root_path,
                                          self.data_path))

        '''
        df_raw.columns: ['date', ...(other features), target feature]
        '''
        cols = list(df_raw.columns)
        cols.remove(self.target)
        cols.remove('date')
        df_raw = df_raw[['date'] + cols + [self.target]]
        num_train = int(len(df_raw) * 0.7)
        num_test = int(len(df_raw) * 0.2)
        num_vali = len(df_raw) - num_train - num_test
        border1s = [0, num_train - self.seq_len, len(df_raw) - num_test - self.seq_len]
        border2s = [num_train, num_train + num_vali, len(df_raw)]
        border1 = border1s[self.set_type]
        border2 = border2s[self.set_type]

        if self.features == 'M' or self.features == 'MS':
            cols_data = df_raw.columns[1:]
            df_data = df_raw[cols_data]
        elif self.features == 'S':
            df_data = df_raw[[self.target]]

        if self.scale:
            if self.freeze_scaler and self.scaler_path:
                if self._load_external_scaler(df_data.values):
                    data = self.scaler.transform(df_data.values)
                else:
                    data = df_data.values
            elif self.freeze_scaler:
                # no external scaler; fall back to no scaling to avoid fitting on target
                data = df_data.values
            else:
                train_data = df_data[border1s[0]:border2s[0]]
                self.scaler.fit(train_data.values)
                data = self.scaler.transform(df_data.values)
        else:
            data = df_data.values

        df_stamp = df_raw[['date']][border1:border2]
        df_stamp['date'] = pd.to_datetime(df_stamp.date)
        if self.timeenc == 0:
            df_stamp['month'] = df_stamp.date.apply(lambda row: row.month, 1)
            df_stamp['day'] = df_stamp.date.apply(lambda row: row.day, 1)
            df_stamp['weekday'] = df_stamp.date.apply(lambda row: row.weekday(), 1)
            df_stamp['hour'] = df_stamp.date.apply(lambda row: row.hour, 1)
            data_stamp = df_stamp.drop(['date'], 1).values
        elif self.timeenc == 1:
            tf = time_features(pd.to_datetime(df_stamp['date'].values), freq=self.freq)
            data_stamp = tf.transpose(1, 0)
            month = df_stamp.date.apply(lambda row: row.month, 1).values.reshape(-1, 1)
            day = df_stamp.date.apply(lambda row: row.day, 1).values.reshape(-1, 1)
            weekday = df_stamp.date.apply(lambda row: row.weekday(), 1).values.reshape(-1, 1)
            hour = df_stamp.date.apply(lambda row: row.hour, 1).values.reshape(-1, 1)
            doy = df_stamp.date.apply(lambda row: row.dayofyear, 1).values.reshape(-1, 1)
            time_hour_idx = ((doy - 1) * 24 + hour).reshape(-1, 1)
            extras = np.concatenate([month, day, weekday, hour, doy, time_hour_idx], axis=1)
            data_stamp = np.concatenate([data_stamp, extras], axis=1)

        self.data_x = data[border1:border2]
        self.data_y = data[border1:border2]
        self.data_stamp = data_stamp
        # keep raw datetime list for image alignment
        self.date_list = df_stamp['date'].values
        if 'capacity' in df_raw.columns:
            try:
                self.capacity_max = float(df_raw['capacity'].max())
            except Exception:
                self.capacity_max = None
        # build image index if provided
        self.img_index = None
        self.img_times = None
        if self.cloud_dir:
            self._build_img_index()

    def _load_external_scaler(self, data_arr):
        """
        Load a pre-fit MinMax scaler (npz with data_min and data_max or sklearn pickle).
        Falls back to unscaled if loading fails.
        """
        try:
            path = self.scaler_path
            if path.endswith(".npz"):
                stats = np.load(path)
                data_min = stats["data_min"]
                data_max = stats["data_max"]
            else:
                import joblib
                scaler = joblib.load(path)
                # assume it's a MinMaxScaler
                self.scaler = scaler
                return True
            data_min = np.array(data_min)
            data_max = np.array(data_max)
            data_range = data_max - data_min
            scale = (self.scaler.feature_range[1] - self.scaler.feature_range[0]) / data_range
            min_ = self.scaler.feature_range[0] - data_min * scale
            self.scaler.scale_ = scale
            self.scaler.min_ = min_
            self.scaler.data_min_ = data_min
            self.scaler.data_max_ = data_max
            self.scaler.data_range_ = data_range
            self.scaler.n_samples_seen_ = data_arr.shape[0]
            return True
        except Exception as e:
            print(f"[WARN] failed to load external scaler from {self.scaler_path}: {e}. Using raw values.")
            return False

    def _build_img_index(self):
        paths = glob.glob(os.path.join(self.cloud_dir, "**", "*.png"), recursive=True)
        times = []
        keep = []
        pat = re.compile(r".*?(\\|/)(\\d{8})_(\\d{4}).*?\\.png", re.IGNORECASE)
        for p in paths:
            m = pat.match(p)
            if not m:
                m = re.search(r"(\\d{8})_(\\d{4})", os.path.basename(p))
            if m:
                date_str, time_str = m.groups()[-2:]
                try:
                    dt = datetime.strptime(date_str + time_str, "%Y%m%d%H%M")
                    times.append(dt)
                    keep.append(p)
                except Exception:
                    continue
        if len(keep) == 0:
            return
        # sort
        times_np = np.array(times)
        order = np.argsort(times_np)
        self.img_times = [times_np[i] for i in order]
        self.img_index = [keep[i] for i in order]

    def _load_img(self, path):
        try:
            img = Image.open(path).convert("L" if self.img_channel == 1 else "RGB")
            img = img.resize((self.img_size, self.img_size), Image.BICUBIC)
            arr = np.asarray(img).astype(np.float32) / 255.0
            if self.img_channel == 1:
                arr = arr[None, ...]  # [1,H,W]
            else:
                arr = arr.transpose(2, 0, 1)
            return arr
        except Exception:
            return np.zeros((self.img_channel, self.img_size, self.img_size), dtype=np.float32)

    def _nearest_img(self, dt):
        if self.img_index is None or self.img_times is None or len(self.img_times) == 0:
            return np.zeros((self.img_channel, self.img_size, self.img_size), dtype=np.float32)
        ts = np.array([t.timestamp() for t in self.img_times])
        tgt = dt.timestamp()
        idx = int(np.argmin(np.abs(ts - tgt)))
        return self._load_img(self.img_index[idx])

    def __getitem__(self, index):
        s_begin = index
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len

        seq_x = self.data_x[s_begin:s_end]
        seq_y = self.data_y[r_begin:r_end]
        seq_x_mark = self.data_stamp[s_begin:s_end]
        seq_y_mark = self.data_stamp[r_begin:r_end]

        if self.cloud_dir:

            stamps = self.date_list[r_begin:r_end]
            imgs = []
            for ts in stamps:
                if isinstance(ts, np.datetime64):
                    ts = pd.to_datetime(ts).to_pydatetime()
                imgs.append(self._nearest_img(ts))
            imgs = np.stack(imgs, axis=0)  # [L, C, H, W]
            return seq_x, seq_y, seq_x_mark, seq_y_mark, imgs
        else:
            return seq_x, seq_y, seq_x_mark, seq_y_mark

    def __len__(self):
        return len(self.data_x) - self.seq_len - self.pred_len + 1

    def inverse_transform(self, data):
        return self.scaler.inverse_transform(data)


